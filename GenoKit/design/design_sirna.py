# -*- coding: utf-8 -*-
"""siRNA candidate generation and filtering.

Candidates are stored as the sense sequence found in the target transcript.
The experimental guide strand is its reverse complement and is generated by
the command layer when writing results.
"""

import logging
import re
from collections import defaultdict
from typing import Dict, List, Tuple
from GenoKit.database.kmer_database import kmer_frequencies


class SirnaDesigner:
    """Design siRNA candidates from one or more mature transcript sequences."""

    def __init__(
        self,
        gene_name: str,
        transcripts: Dict[str, str],
        kmer_bin: Dict[str, int] | None = None,
        min_gc: float = 0.30,
        max_gc: float = 0.50,
        si_length: int = 21,
    ):
        if si_length < 15:
            raise ValueError("siRNA length must be at least 15 nt")
        if not 0 <= min_gc <= max_gc <= 1:
            raise ValueError("GC range must satisfy 0 <= min_gc <= max_gc <= 1")

        self.gene_name = gene_name
        self.kmer_bin = kmer_bin or {}
        self.min_gc = min_gc
        self.max_gc = max_gc
        self.length = si_length
        self.candidates: Dict[str, set[str]] = defaultdict(set)
        self._candidate_positions: Dict[str, Dict[str, List[int]]] = defaultdict(
            lambda: defaultdict(list)
        )
        self.sirnas: List[Dict] = []
        self._repeat_pattern = re.compile(r"(.)\1{2,}")
        self.transcripts = self._preprocess_sequences(transcripts)

    def _preprocess_sequences(self, transcripts: Dict[str, str]) -> Dict[str, str]:
        """Preserve input transcripts and coordinates, including unscannable ones."""
        valid_sequences = {}
        for transcript_id, sequence in transcripts.items():
            sequence = sequence.upper()
            if len(sequence) < self.length:
                logging.warning(
                    "Transcript %s is shorter than %d nt; it has no candidates but remains an all-mode target.",
                    transcript_id,
                    self.length,
                )
            valid_sequences[transcript_id] = sequence
        return valid_sequences

    def generate_candidates(self) -> None:
        """Generate every overlapping fixed-length target window once.

        An ``AA`` start remains a ranking preference in :meth:`filter_sirnas`,
        instead of incorrectly excluding all other valid candidate windows.
        """
        self.candidates.clear()
        self._candidate_positions.clear()
        for transcript_id, sequence in self.transcripts.items():
            for start in range(len(sequence) - self.length + 1):
                candidate = sequence[start : start + self.length]
                if re.search(r"[^ATCG]", candidate):
                    continue
                self.candidates[candidate].add(transcript_id)
                self._candidate_positions[candidate][transcript_id].append(start)

    def filter_sirnas(self, require_all: bool = True, avoid_repeats: int = 3,
                      *, target_mode: str | None = None) -> None:
        """Filter and rank candidates without changing their DNA sequence.

        ``kmer_freq`` is deliberately kept separate from ``sequence``.  This
        prevents the frequency annotation from corrupting GC calculations,
        repeat filtering, or transcript-position lookup.
        """
        if target_mode is not None:
            if target_mode not in {'all', 'any'}:
                raise ValueError("target_mode must be 'all' or 'any'")
            require_all = target_mode == 'all'
        if avoid_repeats < 2:
            raise ValueError("avoid_repeats must be at least 2")

        target_transcripts = set(self.transcripts)
        repeat_pattern = re.compile(r"(.)\1{%d}" % (avoid_repeats - 1))
        filtered = []
        frequency_by_sequence = kmer_frequencies(self.kmer_bin, self.candidates)
        for sequence, transcript_ids in self.candidates.items():
            if require_all and transcript_ids != target_transcripts:
                continue

            gc_content = (sequence.count("G") + sequence.count("C")) / self.length
            if not self.min_gc <= gc_content <= self.max_gc:
                continue
            if repeat_pattern.search(sequence):
                continue

            # Historical AA/T preference is retained as a ranking signal only.
            priority = 1 if sequence.startswith(("AA", "T")) else 0
            positions = {
                transcript_id: list(self._candidate_positions[sequence][transcript_id])
                for transcript_id in sorted(transcript_ids)
            }
            filtered.append(
                {
                    "sequence": sequence,
                    "gc_content": round(gc_content, 4),
                    "targets": len(transcript_ids),
                    "positions": positions,
                    # Kept for API compatibility with earlier callers.
                    "start_pos": positions,
                    "priority": priority,
                    "kmer_freq": frequency_by_sequence.get(sequence, 0),
                }
            )

        self.sirnas = sorted(
            filtered,
            key=lambda item: (
                -item["priority"],
                abs(item["gc_content"] - 0.45),
                item["kmer_freq"],
                item["sequence"],
            ),
        )

    def _find_positions(self, sequence: str) -> Dict[str, List[int]]:
        """Return zero-based transcript positions for an unmodified candidate."""
        return {
            transcript_id: list(self._candidate_positions.get(sequence, {}).get(transcript_id, []))
            for transcript_id in self.transcripts
        }

    def design(self, require_all: bool = True, *,
               target_mode: str | None = None) -> List[Dict]:
        """Generate/filter candidates; target_mode overrides legacy require_all."""
        if target_mode not in (None, 'all', 'any'):
            raise ValueError("target_mode must be 'all' or 'any'")
        self.generate_candidates()
        self.filter_sirnas(require_all=require_all, target_mode=target_mode)
        return self.sirnas

    def get_top_designs(self, n: int = 5) -> List[Tuple[str, float]]:
        """Return the top ``n`` target sequences and their GC fractions."""
        return [(item["sequence"], item["gc_content"]) for item in self.sirnas[:n]]


if __name__ == "__main__":
    # 使用示例
    test_transcripts = {
        "NM_001": "ATGCTAGCTAGCTAGCTAGCTAGCTAGCTAGCTAGCTAGCTAGCTAGCGCGATCGATCGATCGATCGA",
        "NM_002": "ATCGATCGATCGATCGATCGATAGCTAGCTAGCTAGCTAGCTAGCTAGCTAGCTAGCTAGCTAGC",
    }

    designer = SirnaDesigner("TP53", test_transcripts, kmer_bin=None, si_length=22)

    # 设计靶向所有转录本的 siRNA
    universal = designer.design(require_all=True)
    print("找到 %d 条通用 siRNA:" % len(universal))
    print(designer.get_top_designs(3))

    # 设计靶向任意转录本的 siRNA
    any_transcript = designer.design(require_all=False)
    print("\n找到 %d 条任意靶向 siRNA:" % len(any_transcript))
    print(designer.get_top_designs(3))
